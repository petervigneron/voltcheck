-- 0122 — the day's trend rows join in bulk, not one car at a time.
--
-- WHAT BROKE. The nightly's finalize-audits job failed on 9 of the 12 nights
-- 2026-11-05..16 at one step: refresh_vin_variants('ev_price_trend_ask_daily')
-- cancelled at service_role's 60 s (57014), first try and the retry ten
-- minutes later. The nights it passed it took 35–56 s. ev_price_trend_ask_daily
-- stopped at 2026-11-11, so the Market trends chart on every listing page —
-- a Pro benefit — ended six days ago.
--
-- WHY. Not the fold (0104/0105) and not the backlog. price_trend_day_rows
-- itself: timed alone on 2026-11-17 against the state at the 11-12 close, it
-- ran past 120 s. Its pieces are quick — reading every car's chain price is
-- 6.2 s, the trim-key join 8.2 s, ev_price_model 0.3 s. The plan is what is
-- slow. `s` is a UNION ALL of two branches behind one-time filters, each
-- filtered on a CASE expression the planner has no statistics for, so it
-- expects a handful of rows out of it where there are ~400,000 — and joins
-- them to `listings` and then to `vin_trend_key` by nested loop: two index
-- probes per car, ~800,000 random reads on a box whose cache does not hold
-- them. It is 0105's failure again (a row estimate of ~1 choosing a nested
-- loop) in the function next door.
--
-- THE FIX is 0105's too. With nested loops off for this function the same
-- call returned 10,581 rows in 21.1 s (same day, same state, same minute).
-- Hash joins over 400k rows are the right plan at this size and stay right as
-- it grows; nothing in this function wants a nested loop. The setting is on
-- the function, so it applies to this statement and nothing else, and it
-- changes the plan only — the rows are the same rows.
--
-- REJECTED: materialising `s` in an ANALYZEd temp table as 0105 did. That
-- needs plpgsql and a VOLATILE function; this one is STABLE SQL, and the
-- setting does the same job in one line. Raising the 60 s cap: the cap is what
-- noticed.

alter function public.price_trend_day_rows(date) set enable_nestloop = off;
