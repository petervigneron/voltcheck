#!/usr/bin/env node
// Builds web/data/utility-zips.json: for every live utility program in the
// incentive registry, the ZIP codes its utility serves, so a car page can
// show a shopper only the programs whose territory holds their ZIP
// (lib/incentives/territory.ts).
//
// Inputs, all public-domain federal data, passed as paths:
//   1. EIA-861 "Utility ZIP code" tables as published on OpenEI
//      (iou_zipcodes_YYYY.csv and non_iou_zipcodes_YYYY.csv, columns
//      zip,eiaid,utility_name,state,...), matched on `jurisdiction.eiaIds`.
//   2. The Census 2020 ZCTA-to-county relationship file
//      (tab20_zcta520_county20_natl.txt, pipe-separated), for the community
//      choice aggregators the EIA table never lists: `jurisdiction.counties`
//      names their counties by FIPS, and a program may also carry an
//      explicit `jurisdiction.zips` list.
// A utility program carrying none of the three fields gets no entry, and the
// lookup keeps it for every ZIP in its state (it cannot narrow, so it does
// not pretend to).
//
//   node scripts/build-utility-zips.mjs \
//     path/to/iou_zipcodes_2023.csv path/to/non_iou_zipcodes_2023.csv \
//     path/to/tab20_zcta520_county20_natl.txt
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const [iou, nonIou, zctaCounty] = process.argv.slice(2);
if (!iou || !nonIou || !zctaCounty) {
  console.error("usage: build-utility-zips.mjs <iou.csv> <non_iou.csv> <zcta_county.txt>");
  process.exit(2);
}

const registry = JSON.parse(readFileSync(join(here, "../data/incentive-programs.json"), "utf8"));

// EIA rows: zip → state (first seen wins; a ZIP straddling a line is rare and
// the state programs are the coarse layer anyway), and eiaid → zips.
const zipState = {};
const byEia = new Map();
for (const file of [iou, nonIou]) {
  const lines = readFileSync(file, "utf8").replace(/^﻿/, "").split(/\r?\n/);
  const head = lines[0].split(",");
  const ix = (k) => head.indexOf(k);
  const iz = ix("zip"), ie = ix("eiaid"), is = ix("state");
  for (const line of lines.slice(1)) {
    if (!line) continue;
    // utility_name may be quoted with commas; the three columns we read sit
    // before it (zip, eiaid) or after a fixed tail (state is column 4 only
    // when the name is unquoted), so parse properly.
    const cells = parseCsv(line);
    const zip = cells[iz].padStart(5, "0");
    if (!/^\d{5}$/.test(zip)) continue;
    zipState[zip] ??= cells[is];
    const id = Number(cells[ie]);
    if (!byEia.has(id)) byEia.set(id, new Set());
    byEia.get(id).add(zip);
  }
}

// Census: county FIPS → zips.
const byCounty = new Map();
{
  const lines = readFileSync(zctaCounty, "utf8").replace(/^﻿/, "").split(/\r?\n/);
  const head = lines[0].split("|");
  const iz = head.indexOf("GEOID_ZCTA5_20"), ic = head.indexOf("GEOID_COUNTY_20");
  for (const line of lines.slice(1)) {
    const c = line.split("|");
    const zip = c[iz], county = c[ic];
    if (!zip || !county) continue;
    if (!byCounty.has(county)) byCounty.set(county, new Set());
    byCounty.get(county).add(zip);
  }
}

const programs = {};
const missing = [];
for (const p of registry.programs) {
  if (p.status !== "live" || p.jurisdiction.kind !== "utility") continue;
  const j = p.jurisdiction;
  const zips = new Set(j.zips ?? []);
  for (const id of j.eiaIds ?? []) {
    const z = byEia.get(id);
    if (!z) throw new Error(`${p.id}: EIA id ${id} not in the ZIP tables`);
    for (const zip of z) zips.add(zip);
  }
  for (const county of j.counties ?? []) {
    const z = byCounty.get(county);
    if (!z) throw new Error(`${p.id}: county ${county} not in the Census file`);
    for (const zip of z) zips.add(zip);
  }
  if (zips.size === 0) {
    missing.push(p.id);
    continue;
  }
  programs[p.id] = [...zips].sort();
}

// Three-digit prefix → state for ZIPs the EIA tables never mention.
const prefixVotes = {};
for (const [zip, st] of Object.entries(zipState)) {
  const k = zip.slice(0, 3);
  prefixVotes[k] ??= {};
  prefixVotes[k][st] = (prefixVotes[k][st] ?? 0) + 1;
}
const prefixState = {};
for (const [k, votes] of Object.entries(prefixVotes)) prefixState[k] = Object.entries(votes).sort((a, b) => b[1] - a[1])[0][0];

const out = {
  _comment:
    "Generated by scripts/build-utility-zips.mjs from EIA-861 utility ZIP tables (OpenEI, 2023) and the Census 2020 ZCTA-county file. Do not edit; rerun the script.",
  zipState,
  prefixState,
  programs,
};
writeFileSync(join(here, "../data/utility-zips.json"), JSON.stringify(out));
console.log(`zips with a state: ${Object.keys(zipState).length}; prefixes: ${Object.keys(prefixState).length}`);
for (const [id, z] of Object.entries(programs)) console.log(`${id.padEnd(44)} ${z.length} zips`);
if (missing.length) console.log(`no territory data (kept statewide): ${missing.join(", ")}`);

function parseCsv(line) {
  const out = [];
  let cur = "", q = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (q) {
      if (ch === '"' && line[i + 1] === '"') { cur += '"'; i++; }
      else if (ch === '"') q = false;
      else cur += ch;
    } else if (ch === '"') q = true;
    else if (ch === ",") { out.push(cur); cur = ""; }
    else cur += ch;
  }
  out.push(cur);
  return out;
}
